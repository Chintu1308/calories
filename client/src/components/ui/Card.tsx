import React from 'react';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  interactive?: boolean;
}

export const Card: React.FC<CardProps> = ({
  children,
  interactive = false,
  className = '',
  ...props
}) => {
  const interactiveClass = interactive ? 'calories-card--interactive' : '';
  return (
    <div className={`calories-card ${interactiveClass} ${className}`} {...props}>
      {children}
    </div>
  );
};

